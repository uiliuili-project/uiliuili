import 'dotenv/config';
import path from 'node:path';

function bool(value: string | undefined, fallback = false): boolean {
  if (value === undefined) return fallback;
  return ['1', 'true', 'yes', 'on'].includes(value.toLowerCase());
}

function number(value: string | undefined, fallback: number): number {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}

export const config = {
  nodeEnv: process.env.NODE_ENV ?? 'development',
  production: process.env.NODE_ENV === 'production',
  appUrl: process.env.APP_URL ?? 'http://localhost:3000',
  apiPort: number(process.env.API_PORT, 3001),
  databaseUrl: process.env.DATABASE_URL ?? '',
  appKey: process.env.APP_KEY ?? '',
  redisUrl: process.env.REDIS_URL ?? '',
  trustProxy: bool(process.env.TRUST_PROXY),
  storageRoot: path.resolve(process.env.STORAGE_ROOT ?? './storage/uploads'),
  logLevel: process.env.LOG_LEVEL ?? 'info',
  installAllowLocalhost: bool(process.env.INSTALL_ALLOW_LOCALHOST, true),
  installNoRestart: bool(process.env.INSTALL_NO_RESTART, false),
  ffmpegPath: process.env.FFMPEG_PATH ?? 'ffmpeg',
  ffprobePath: process.env.FFPROBE_PATH ?? 'ffprobe',
  transcodeConcurrency: number(process.env.TRANSCODE_CONCURRENCY, 2),
  isSecure: (process.env.APP_URL ?? '').startsWith('https://'),
};

export function requireInstalledConfig(): void {
  if (!config.databaseUrl) throw new Error('DATABASE_URL is required after installation');
  if (!config.appKey || !/^[0-9a-f]{64}$/.test(config.appKey)) {
    throw new Error('APP_KEY must be a 32-byte hex string generated by the installer');
  }
}
