import type { InstallConfig } from '@uiliuili/shared';
import { writeFileAtomic } from './paths';

function quote(value: string): string {
  if (/^[A-Za-z0-9_./:@-]*$/.test(value)) return value;
  return JSON.stringify(value);
}

export function buildDatabaseUrl(
  config: InstallConfig['database'],
  database = config.database,
): string {
  const user = encodeURIComponent(config.user);
  const password = encodeURIComponent(config.password);
  const host = config.host.includes(':') ? `[${config.host}]` : config.host;
  const ssl = config.ssl ? '?sslmode=require' : '';
  return `postgres://${user}:${password}@${host}:${config.port}/${encodeURIComponent(database)}${ssl}`;
}

export interface EnvFileOptions {
  production: boolean;
  appKey: string;
  apiInternalUrl?: string;
}

export function buildEnvFile(config: InstallConfig, options: EnvFileOptions): string {
  const values: Array<[string, string | undefined]> = [
    ['NODE_ENV', options.production ? 'production' : 'development'],
    ['APP_URL', config.site.url],
    ['API_INTERNAL_URL', options.apiInternalUrl ?? 'http://127.0.0.1:3001'],
    ['NEXT_PUBLIC_API_URL', ''],
    ['DATABASE_URL', buildDatabaseUrl(config.database)],
    ['DB_SCHEMA', config.database.schema],
    ['APP_KEY', options.appKey],
    ['REDIS_URL', config.redis?.url],
    ['MEILISEARCH_URL', config.search.driver === 'meilisearch' ? config.search.url : undefined],
    ['MEILISEARCH_KEY', config.search.driver === 'meilisearch' ? config.search.key : undefined],
    ['API_PORT', '3001'],
    ['TRUST_PROXY', 'false'],
    ['LOG_LEVEL', 'info'],
    [
      'STORAGE_ROOT',
      config.storage.driver === 'local' ? config.storage.localPath : './storage/uploads',
    ],
    ['FFMPEG_PATH', 'ffmpeg'],
    ['FFPROBE_PATH', 'ffprobe'],
    ['TRANSCODE_CONCURRENCY', '2'],
    ['INSTALL_ALLOW_LOCALHOST', options.production ? 'false' : 'true'],
  ];

  const lines = [
    '# Generated by the uiliuili installer. Keep this file private.',
    '# Do not commit it. Back it up together with the database.',
    '',
  ];
  for (const [key, value] of values) {
    if (value !== undefined && value !== '') lines.push(`${key}=${quote(value)}`);
  }
  return `${lines.join('\n')}\n`;
}

export function writeEnvFile(path: string, content: string): void {
  writeFileAtomic(path, content, 0o600);
}
